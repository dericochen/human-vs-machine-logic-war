// Generates the 100-round seed SQL from the deterministic bank generator.
// The output is idempotent (ON CONFLICT DO NOTHING) and mirrors the fallback
// bank used when Supabase is not configured.
//
// Run:  node scripts/seed-bank.ts

import { generateBank } from "../lib/game/bank.ts";
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const bank = generateBank();

function q(s: string): string {
  return "'" + s.replace(/'/g, "''") + "'";
}
function j(v: unknown): string {
  return q(JSON.stringify(v));
}

const PROMPT = "Find the emoji that is different.";

const rows = bank
  .map((r) => {
    return (
      "(" +
      [
        q(r.id),
        q("odd_emoji"),
        q(r.difficulty),
        q("grid"),
        q(PROMPT),
        String(r.gridSize),
        j(r.cells) + "::jsonb",
        q(r.baseEmoji),
        q(r.oddEmoji),
        String(r.oddIndex),
        q(r.explanation),
        String(r.timeLimitSec),
        String(r.basePoints),
        j(r.params) + "::jsonb",
        q(r.source),
        "true",
        "now()",
      ].join(", ") +
      ")"
    );
  })
  .join(",\n  ");

const sql = [
  "-- Auto-generated by scripts/seed-bank.ts. Do not edit by hand.",
  `-- ${bank.length} validated "find the different emoji" rounds (25 per difficulty).`,
  "",
  "INSERT INTO question_bank",
  "  (id, category, difficulty, kind, prompt, grid_size, cells, base_emoji, odd_emoji,",
  "   odd_index, explanation, time_limit_sec, base_points, params, source, active, created_at)",
  "VALUES",
  "  " + rows,
  "ON CONFLICT (id) DO NOTHING;",
  "",
].join("\n");

const outDir = join(root, "supabase", "migrations");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "0002_seed_bank.sql"), sql, "utf8");

console.log(`Wrote ${bank.length} rounds to supabase/migrations/0002_seed_bank.sql`);
